const skuIndex = new Map()

for (const category of productCategories) {
  for (const item of category.items) {
    skuIndex.set(item.sku, { ...item, categorySlug: category.slug, categoryName: category.name })
  }
}

export function findProductBySku(sku) {
  return skuIndex.get(sku) ?? null
}

export function calculateCartTotals(lineItems) {
  const resolved = []
  let subtotal = 0

  for (const line of lineItems) {
    const product = findProductBySku(line.sku)
    if (!product) {
      throw new Error(`Unknown product: ${line.sku}`)
    }
    const quantity = Math.max(1, Math.min(99, Number(line.quantity) || 1))
    const lineTotal = product.priceInRupees * quantity
    subtotal += lineTotal
    resolved.push({
      sku: product.sku,
      name: product.name,
      categoryName: product.categoryName,
      quantity,
      unitPrice: product.priceInRupees,
      lineTotal,
      image: product.image,
      price: product.price,
    })
  }

  const shippingCharge = subtotal > 0 ? 49 : 0
  const gstAmount = Math.round(subtotal * 0.05 * 100) / 100
  const total = Math.round((subtotal + shippingCharge + gstAmount) * 100) / 100
  const amountPaise = Math.round(total * 100)

  return {
    items: resolved,
    subtotal,
    shippingCharge,
    gstAmount,
    total,
    amountPaise,
  }
}
